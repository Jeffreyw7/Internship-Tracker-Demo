import type {ApplicationDraft} from '../domain/application.ts';
import {toPayload} from './applicationApi.ts';

export interface CreatePointer {ownerId:string;key:string;fingerprint:string}
const storageKey=(ownerId:string)=>`campus:create:${ownerId}`;
const uuid=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
export function readCreatePointer(storage:Storage|undefined,ownerId:string):CreatePointer|null {
  try {
    const value:unknown=JSON.parse(storage?.getItem(storageKey(ownerId))??'null');
    if(value&&typeof value==='object'&&'ownerId' in value&&value.ownerId===ownerId&&'key' in value&&typeof value.key==='string'&&uuid.test(value.key)&&'fingerprint' in value&&typeof value.fingerprint==='string'&&/^[0-9a-f]{64}$/.test(value.fingerprint))return value as CreatePointer;
  } catch { /* Unavailable tab storage is reported before a new create dispatch. */ }
  return null;
}
export function rememberCreate(storage:Storage|undefined,pointer:CreatePointer) {
  try {
    if(!storage)throw new Error('No tab storage');
    storage.setItem(storageKey(pointer.ownerId),JSON.stringify(pointer));
    if(storage.getItem(storageKey(pointer.ownerId))!==JSON.stringify(pointer))throw new Error('Tab storage did not retain the reference');
  } catch {throw new Error('Tab storage is unavailable. Enable it before adding an application so an interrupted save can be recovered.');}
}
export function forgetCreate(storage:Storage|undefined,pointer:CreatePointer) {
  try {if(readCreatePointer(storage,pointer.ownerId)?.key===pointer.key)storage?.removeItem(storageKey(pointer.ownerId));} catch { /* A retained reference can safely be checked again. */ }
}
export async function createFingerprint(draft:ApplicationDraft):Promise<string> {
  const payload=toPayload(draft);
  // Stage IDs are generated by the server on creation; only editable values identify this attempt.
  const canonical={...payload,stages:payload.stages.map(({name,date,state})=>({name,date,state}))};
  const bytes=await crypto.subtle.digest('SHA-256',new TextEncoder().encode(JSON.stringify(canonical)));
  return Array.from(new Uint8Array(bytes),byte=>byte.toString(16).padStart(2,'0')).join('');
}
